async function main() {
  console.log("🌱 Seeding static pages...");
  for (const page of PAGES) {
    await prisma.staticPage.upsert({
      where: { slug: page.slug },
      update: page,
      create: page,
    });
    console.log(`  ✅ ${page.slug}`);
  }
  console.log("🎉 Done!");
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
