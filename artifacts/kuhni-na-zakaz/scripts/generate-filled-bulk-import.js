function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function copyImages() {
  ensureDir(targetImagesDir);
  for (const item of imagePlan) {
    const source = path.join(sourceImagesDir, item.source);
    const target = path.join(targetImagesDir, item.target);
    if (!fs.existsSync(source)) {
      throw new Error(`Source image not found: ${source}`);
    }
    fs.copyFileSync(source, target);
  }
}

