function writeWorkbook() {
  const wb = XLSX.readFile(templatePath);

  for (const sheetName of Object.keys(sheetData)) {
    const rows = sheetData[sheetName];
    const headerRow = XLSX.utils.sheet_to_json(wb.Sheets[sheetName], {
      header: 1,
      blankrows: false,
      range: 0,
    })[0];

    const sheet = XLSX.utils.json_to_sheet(rows, { header: headerRow, skipHeader: false });
    wb.Sheets[sheetName] = sheet;
  }

  XLSX.writeFile(wb, outputPath);
}

