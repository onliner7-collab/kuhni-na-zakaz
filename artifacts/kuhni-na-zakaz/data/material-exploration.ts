export interface MaterialExplorationFrame {
  id: string;
  label: string;
  image: string;
  alt: string;
  result: string;
  caution: string;
}

export interface MaterialExplorationConfig {
  slug: string;
  material: string;
  title: string;
  question: string;
  frames: MaterialExplorationFrame[];
}

function frames(slug: string, material: string, notes: Array<[string, string, string]>) {
  const suffixes = ["a-front", "b-angle", "c-macro", "d-kitchen"];
  return notes.map(([label, result, caution], index) => ({
    id: suffixes[index],
    label,
    image: ["", "images", "materials-gallery-v2", slug, `${slug}-${suffixes[index]}.webp`].join("/"),
    alt: `${material}: ${label.toLowerCase()}, визуальный ориентир для выбора фасада кухни`,
    result,
    caution,
  }));
}

