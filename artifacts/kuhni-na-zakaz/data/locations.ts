function location(data: Omit<RegionalLocationData, "title" | "description" | "introText" | "seoText" | "warrantyText" | "isMainRegion" | "portfolioCityKey" | "areas"> & {
  seoText: string;
  warrantyText?: string;
  portfolioCityKey?: string;
  areas?: string[];
}): RegionalLocationData {
  return {
    ...data,
    title: data.pageTitle,
    description: data.metaDescription,
    introText: data.intro,
    portfolioCityKey: data.portfolioCityKey ?? data.cityName,
    areas: data.areas ?? data.nearbyAreas.map((area) => area.label),
    warrantyText:
      data.warrantyText ??
      "Гарантия на корпус, фасады, фурнитуру и монтаж фиксируется в договоре. Все спорные вопросы ведем через одного исполнителя, без поиска сторонних подрядчиков.",
    isMainRegion: data.isMajorCity || data.slug === "minsk" || data.slug === "minskaya-oblast",
  };
}

